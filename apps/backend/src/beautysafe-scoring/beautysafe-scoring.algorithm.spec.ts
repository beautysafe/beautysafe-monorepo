describe('BeautySafe scoring algorithm', () => {
  it.each(references)(
    'matches Python reference product %#',
    (ingredients, expected) => {
      expect(calculateBeautySafeScore(parseScoredList(ingredients)).score).toBe(
        expected,
      );
    },
  );

  it('returns an unreliable result for an empty composition', () => {
    expect(calculateBeautySafeScore([])).toMatchObject({
      score: 100,
      recognitionRate: 0,
      reliable: false,
    });
  });

  it('rejects an invalid ingredient score', () => {
    expect(() =>
      calculateBeautySafeScore([
        { name: 'Invalid', score: 7 as BeautySafeIngredientInput['score'] },
      ]),
    ).toThrow('Invalid BeautySafe ingredient score');
  });
});
