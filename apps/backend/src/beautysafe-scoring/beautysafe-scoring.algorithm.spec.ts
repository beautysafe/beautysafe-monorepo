const parseScoredList = (value: string): BeautySafeIngredientInput[] =>
  value.split('|').map((part) => {
    const separator = part.lastIndexOf(':');
    return {
      name: part.slice(0, separator).trim(),
      score: Number(
        part.slice(separator + 1),
      ) as BeautySafeIngredientInput['score'],
    };
  });

